const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  openVideo: () => ipcRenderer.invoke('video:open'),
  listSports: () => ipcRenderer.invoke('sports:list'),
  loadTags: (key) => ipcRenderer.invoke('tags:load', key),
  saveTags: (key, data) => ipcRenderer.invoke('tags:save', key, data),
  loadXbotgoMarks: (videoPath) => ipcRenderer.invoke('xbotgo:marks', videoPath),
  loadTeams: () => ipcRenderer.invoke('teams:load'),
  saveTeams: (data) => ipcRenderer.invoke('teams:save', data),
  loadSettings: () => ipcRenderer.invoke('settings:load'),
  saveSettings: (data) => ipcRenderer.invoke('settings:save', data),
  pickFolder: (title) => ipcRenderer.invoke('folder:pick', title),
  checkAiDir: (dir) => ipcRenderer.invoke('ai:dir:check', dir),
  findAiDir: () => ipcRenderer.invoke('ai:dir:find'),
  loadAiEvents: (dir) => ipcRenderer.invoke('ai:events:load', dir),
  saveAiEvents: (dir, data) => ipcRenderer.invoke('ai:events:save', dir, data),
  pickAiResults: (defaultPath) => ipcRenderer.invoke('ai:import:pick', defaultPath),
  loadAiRun: (exportPath) => ipcRenderer.invoke('ai:run:load', exportPath),
  saveAiPlayers: (base, data) => ipcRenderer.invoke('ai:players:save', base, data),
  refilterAi: (hai, base, startOffset) => ipcRenderer.invoke('ai:refilter', hai, base, startOffset),
  aiGame: (hai, video) => ipcRenderer.invoke('ai:game', hai, video),
  saveAiPicks: (video, picks) => ipcRenderer.invoke('ai:picks:save', video, picks),
  analyzeGame: (hai, video, opts) => ipcRenderer.invoke('ai:analyze', hai, video, opts),
  makeReport: (hai, video, opts) => ipcRenderer.invoke('ai:report', hai, video, opts),
  getAiJob: () => ipcRenderer.invoke('ai:job:get'),
  cancelAiJob: () => ipcRenderer.invoke('ai:job:cancel'),
  onAiJob: (fn) => ipcRenderer.on('ai:job', (_e, job) => fn(job)),
  openFile: (file) => ipcRenderer.invoke('ai:open', file),
  saveVideoAs: (defaultPath) => ipcRenderer.invoke('clips:save-as', defaultPath),
  exportClips: (opts) => ipcRenderer.invoke('clips:export', opts),
  cancelClips: () => ipcRenderer.invoke('clips:cancel'),
  pickLogo: () => ipcRenderer.invoke('logo:pick'),
  savePictureAs: (defaultPath) => ipcRenderer.invoke('frame:save-as', defaultPath),
  saveFrame: (opts) => ipcRenderer.invoke('frame:save', opts),
  showFile: (file) => ipcRenderer.invoke('clips:show', file),
  onClipsProgress: (fn) => ipcRenderer.on('clips:progress', (_e, state) => fn(state)),
  loadCameraMotion: (video) => ipcRenderer.invoke('xbotgo:motion', video),
  scanDeadTime: (video) => ipcRenderer.invoke('autocut:scan', video),
  saveCondensed: (opts) => ipcRenderer.invoke('autocut:save', opts),
  cancelAutoCut: () => ipcRenderer.invoke('autocut:cancel'),
  onAutoCutProgress: (fn) => ipcRenderer.on('autocut:progress', (_e, state) => fn(state)),
  checkFfmpeg: () => ipcRenderer.invoke('ffmpeg:check'),
});
